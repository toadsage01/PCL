/* ============================================================================
   PCL FORM CAT — the smug guardian of the submit button.
   ----------------------------------------------------------------------------
   One cat, two lives (posture follows the theme, like a real cat):
     · light mode  — lying flat on its side, cheek resting on its front
                     paws, eyes open and heavy-lidded, smirking straight
                     at the viewer (modeled on the user's own cat, photo
                     #2). White fur, grey-brown tabby saddle + striped
                     tail, ginger cap over the right ear/eye, pink nose,
                     maroon collar with a gold bell.
     · dark mode   — awake, sitting upright, turned 45° from the screen
                     plane toward the viewer; fur looks greyer in the dim
                     light and the amber eyes glow.

   THE EVENT (one event, gated by two conditions): the cursor moves onto
   the Complete/Send button WHILE some required field is still empty →
   the cat uncurls one front paw and SHOVES the button a little more to
   the right — a random 2/3 to 2x of the button's own width — exactly
   ONCE per visit. THE CAT NEVER MOVES ITSELF: only the paw frames swap
   and only the button travels. After the shove: no alteration, no
   further visual events. The button rests in its new spot, fully
   clickable. If they click it anyway with fields still empty, the angry
   pointer from phase 2 takes over (js/finger-slam.js).

   Motion budget: transform-only (Web Animations API) + steps() easing for
   the chunky pixel shove — GPU-composited, zero reflow, snappy at any FPS.
   prefers-reduced-motion: the button lands in its shoved spot instantly.
   ========================================================================== */

