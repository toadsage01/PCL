  function buildRows(base, patches) {
    var grid = base.map(function (r) {
      return r.split("");
    });
    (patches || []).forEach(function (p) {
      if (grid[p[0]]) grid[p[0]][p[1]] = p[2];
    });
    return grid;
  }
  function blit(rows, dx, dy) {          // park a small map on the canvas
    var out = [];
    for (var r = 0; r < CH; r++) {
      var src = rows[r - dy], row = [];
      for (var c = 0; c < CW; c++) {
        var ch = (src && src[c - dx]) || ".";
        row.push(ch);
      }
      out.push(row);
    }
    return out;
  }
  function theme() {
    return document.documentElement.getAttribute("data-pcl-theme") === "dark"
      ? "dark" : "light";
  }
  function frames(kind) {
    var dark = theme() === "dark";
    if (dark) {
      var patch = kind === "reach" ? SIT_REACH
                : kind === "push"  ? SIT_PUSH : null;
      return { rows: blit(buildRows(SIT, patch), SIT_DX, SIT_DY), y: 0 };
    }
    return kind === "reach" ? { rows: LOAF_REACH_FULL, y: 0 }
         : kind === "push"  ? { rows: LOAF_PUSH_FULL, y: 0 }
         : { rows: LOAF, y: 0 };
  }

  var host = null, canvas = null, ctx = null, cell = 3;
  function scaleFor() {
    return window.innerWidth < 420 ? 2 : 3;
  }
  function paint(kind) {
    if (!ctx) return;
    var f = frames(kind || "base");
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    var pal = PALETTES[theme()];
    for (var r = 0; r < f.rows.length; r++) {
      var row = f.rows[r];
      for (var c = 0; c < row.length; c++) {
        var ch = row[c];
        if (ch === ".") continue;
        ctx.fillStyle = pal[ch] || "#f0f";
        ctx.fillRect(c, r + f.y, 1, 1);
      }
    }
  }
  function rebuildCanvas() {
    if (!host) return;
    cell = scaleFor();
    var w = CW * cell, h = CH * cell;
    if (!canvas) {
      canvas = document.createElement("canvas");
      host.appendChild(canvas);
    }
    canvas.width = CW; canvas.height = CH;
    canvas.style.width = w + "px";
    canvas.style.height = h + "px";
    ctx = canvas.getContext("2d");
    ctx.imageSmoothingEnabled = false;
    paint("base");
  }

